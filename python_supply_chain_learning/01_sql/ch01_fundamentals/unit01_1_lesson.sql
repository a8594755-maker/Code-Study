-- ============================================================
-- 步驟 1：這個資料庫裡有哪些 schema（資料表分組）？
-- ============================================================
-- 分析師的問題：業務資料放在哪個分組裡？
-- 為什麼：資料庫像大型 Excel 工作簿，schema 像裡面的資料夾，
-- table（資料表）像一張張工作表。先找對資料夾，才不會查錯地方。

SELECT schema_name
FROM information_schema.schemata
ORDER BY schema_name;

-- SELECT（選取要顯示的欄位）＋ FROM（指定資料來源）＋ ORDER BY（排序）。
-- information_schema（資料庫目錄）＝ PostgreSQL 內建說明書：記錄資料庫裡有什麼，本身不是業務資料。
-- 執行後看什麼：清單裡找到 olist；pg_ 開頭的是系統自用，跳過。
-- 寫下你的觀察：業務資料所在的 schema 是 __________

-- ============================================================
-- 步驟 2：olist 裡有哪些表？
-- ============================================================
-- 分析師的問題：我手上到底有幾張表可以用？
-- 為什麼：分析師不猜表名，先查目錄拿完整清單——就像打開活頁簿先看有哪些工作表分頁。

SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'olist'
ORDER BY table_name;

-- WHERE（篩選條件）是 ch02 的主角，今天先借用這一行：只留 olist 的表。
-- 執行後看什麼：應該出現 9 張名字以 _raw 結尾的表。
-- 寫下你的觀察：看名字猜，跟「訂單」有關的表是 __________

-- ============================================================
-- 步驟 3：每張表有多少筆資料？
-- ============================================================
-- 分析師的問題：哪些是大表、哪些是小表？
-- 為什麼：筆數透露角色——幾萬筆通常是交易資料，幾十筆通常是對照表。
-- 一次數一張，先數訂單表：

SELECT COUNT(*) AS order_row_count
FROM olist.orders_raw;

-- COUNT(*)（計算列數）數出有幾個 row（資料列；一列＝一筆訂單）；AS（別名）讓結果欄好讀。
-- 執行後看什麼：大約 99,441 筆。接著數最大的一張：

SELECT COUNT(*) AS geo_row_count
FROM olist.geolocation_raw;

-- 執行後看什麼：約 100 萬筆！這正是 LIMIT（限制列數）存在的理由——
-- 對這種表若不加 LIMIT 就撈全部，等於叫資料庫把 100 萬列都送到你
-- 電腦上，又慢又沒必要。之後預覽任何表，習慣性先加 LIMIT。
-- （想數其他表？把 FROM 後面的表名換掉再跑一次就行。）
-- 寫下你的觀察：orders_raw ______ 筆；geolocation_raw ______ 筆。

-- ============================================================
-- 步驟 4：一筆訂單長什麼樣？
-- ============================================================
-- 分析師的問題：orders_raw 的一列到底記了什麼？
-- 為什麼：光看表名會騙人，打開看 10 筆真實資料最誠實。

SELECT *
FROM olist.orders_raw
LIMIT 10;

-- * 代表「全部 column（欄位）」，搭配 LIMIT 10 只拿前 10 列，安全又快。
-- 執行後看什麼：每列一個 order_id；order_status 有 delivered 等狀態；
-- 幾個日期欄記錄下單、出貨、送達——這是之後交期分析的原料。
-- 寫下你的觀察：orders_raw 的一列代表 __________

-- ============================================================
-- 步驟 5：只挑需要的欄位
-- ============================================================
-- 分析師的問題：做訂單狀態報告，其實只需要哪幾欄？
-- 為什麼：SELECT * 適合第一眼；正式工作要點名欄位才好讀好解釋——像 Excel 報表只留必要欄。

SELECT
    order_id,
    order_status,
    order_purchase_timestamp
FROM olist.orders_raw
LIMIT 10;

-- 欄位名用逗號分隔，寫的順序就是結果的欄位順序。
-- 執行後看什麼：比 SELECT * 乾淨多了，一眼看懂每筆訂單的狀態與時間。
-- 寫下你的觀察：這三欄各回答了什麼問題？__________

-- ============================================================
-- 步驟 6：最新的訂單是什麼時候？
-- ============================================================
-- 分析師的問題：這份資料涵蓋到什麼時候？是最新的嗎？
-- 為什麼：先確認資料的時間範圍，才不會把歷史資料當成現況來報告。

SELECT
    order_id,
    order_status,
    order_purchase_timestamp
FROM olist.orders_raw
ORDER BY order_purchase_timestamp DESC
LIMIT 10;

-- ORDER BY 指定排序欄位；DESC（遞減）用在日期上就是「最新排最前」。
-- 執行後看什麼：第一列就是整個資料集最新的一筆訂單。
-- 寫下你的觀察：最新的下單時間是 __________（提示：不是今年！）

